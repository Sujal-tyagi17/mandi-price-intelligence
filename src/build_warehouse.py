"""
Build the DuckDB warehouse from data/interim/raw_prices.parquet.

  1. sql/00_staging.sql   -> cleaned star schema in data/mandi.duckdb
  2. sql/01..NN_*.sql     -> each result saved to data/processed/<name>.csv
  3. data quality report  -> reports/data_quality.md

Run after ingest.py:  python src/build_warehouse.py
"""

from __future__ import annotations

from pathlib import Path

import duckdb

from config import DB_PATH, INTERIM, PROCESSED, REPORTS, SQL_DIR


def build(db_path: Path = DB_PATH, interim: Path = INTERIM, processed: Path = PROCESSED,
          reports: Path = REPORTS) -> dict[str, int]:
    if db_path.exists():
        db_path.unlink()
    con = duckdb.connect(str(db_path))
    con.execute("SET threads TO 1")  # deterministic results on every run
    con.execute((SQL_DIR / "00_staging.sql").read_text().replace("{interim}", interim.as_posix()))

    processed.mkdir(parents=True, exist_ok=True)
    for old in processed.glob("*.csv"):
        old.unlink()
    results = {}
    for path in sorted(SQL_DIR.glob("[0-9][0-9]_*.sql")):
        if path.name.startswith("00_"):
            continue
        name = path.stem[3:]
        df = con.execute(path.read_text()).df()
        df.to_csv(processed / f"{name}.csv", index=False)
        results[name] = len(df)

    write_quality_report(con, reports)
    con.close()
    return results


def write_quality_report(con: duckdb.DuckDBPyConnection, reports: Path) -> None:
    reports.mkdir(parents=True, exist_ok=True)
    log = con.execute("SELECT check_name, rows_affected FROM data_quality_log ORDER BY step").fetchall()
    span = con.execute("SELECT min(price_date), max(price_date), count(DISTINCT market) FROM fact_market_day").fetchone()
    by_source = con.execute("SELECT source, count(*) FROM raw_prices GROUP BY 1 ORDER BY 2 DESC").fetchall()
    crops = con.execute("""
        SELECT commodity, count(DISTINCT market), count(*), round(median(modal_price))
        FROM fact_market_day GROUP BY 1 ORDER BY 1""").fetchall()
    lines = [
        "# Data quality report",
        "",
        "Generated by `src/build_warehouse.py` from the cleaning rules in `sql/00_staging.sql`.",
        "",
        f"- Period covered: **{span[0]} to {span[1]}**",
        f"- Markets: **{span[2]:,}**",
        f"- Raw rows by source: {', '.join(f'{s} {n:,}' for s, n in by_source)}",
        "",
        "## Cleaning steps",
        "",
        "| Check | Rows |",
        "|---|---:|",
    ]
    lines += [f"| {name} | {n:,} |" for name, n in log]
    lines += ["", "## Clean data by crop", "", "| Crop | Markets | Market-days | Median modal price (₹/quintal) |",
              "|---|---:|---:|---:|"]
    lines += [f"| {c} | {m:,} | {d:,} | {p:,.0f} |" for c, m, d, p in crops]
    (reports / "data_quality.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    results = build()
    print(f"Warehouse built at {DB_PATH.name}")
    for name, n in results.items():
        print(f"  {name:<22} {n:>7,} rows -> data/processed/{name}.csv")
    print("Data quality report -> reports/data_quality.md")


if __name__ == "__main__":
    main()
